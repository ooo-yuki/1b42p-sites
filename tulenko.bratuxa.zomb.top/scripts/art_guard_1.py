#!/usr/bin/env python3
"""Круг красоты 1: top_guard_1.png — стражник вид строго сверху, кадр 2 шага.

Верх (ряды 0-11) — пиксель в пиксель как кадр 1 (top_guard_0.png), чтобы анимация
не дёргалась: та же тёмная обводка G, синяя форма B, фуражка S с бликом W,
лицо K, жёлтые руки/ремень Y. Отличие кадра 2 — только ноги в противофазе:
левая нога поднята (короткая, ботинок на рядах 12-13 сдвинут влево),
правая опущена (длинная, ботинок на рядах 14-15). Тени под ногами нет —
её рисует игра.
Повтор: python3 scripts/art_guard_1.py  (из корня tulenko.bratuxa.zomb.top)
"""
from pathlib import Path

from PIL import Image

PAL = {
    ".": (0, 0, 0, 0),
    "B": (52, 102, 220, 255),    # синяя форма
    "G": (58, 62, 72, 255),      # тёмная обводка
    "S": (28, 58, 150, 255),     # тень синяя / фуражка
    "K": (255, 221, 181, 255),   # лицо / руки
    "O": (18, 18, 24, 255),      # глаза / ботинки
    "Y": (255, 210, 60, 255),    # кисти рук / ремень
    "W": (141, 189, 245, 255),   # блик на фуражке
}

# Ряды 0-11 = кадр 1, ряды 12-15 = шаг (левая вверх-влево, правая вниз).
MAP = [
    "................",  # 0
    "................",  # 1
    ".....GGGGG......",  # 2  фуражка
    "....GSSSSSG.....",  # 3
    "...GSSWSSSSG....",  # 4  блик
    "...GBOOOOBG.....",  # 5  козырёк
    "...GBBKKKBBG....",  # 6  лицо
    "..GBBKOKOKBBG...",  # 7  глаза
    "..GBBKKKKKBBG...",  # 8
    ".GYBBBBBBBBBYG..",  # 9  широкие плечи, кисти
    ".GKBBBBBBBSSKG..",  # 10 руки + тень справа
    ".GKBBBGYGBSSKG..",  # 11 ремень Y, тень S
    ".GOOO....BBBG...",  # 12 левый ботинок вперёд-влево / правая нога
    ".GOOO....BSBG...",  # 13 левый ботинок / правая нога в тени
    ".........OOOG...",  # 14 правая нога ушла вниз: ботинок
    ".........OOOG...",  # 15 правый ботинок (шаг назад длиннее)
]

OUT_PATH = Path(__file__).resolve().parent.parent / "img" / "top_guard_1.png"


def main() -> None:
    assert len(MAP) == 16 and all(len(r) == 16 for r in MAP), "карта должна быть 16x16"
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(MAP):
        for x, ch in enumerate(row):
            px[x, y] = PAL[ch]
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    img.save(OUT_PATH)
    print(f"saved {OUT_PATH} size={img.size}")


if __name__ == "__main__":
    main()
