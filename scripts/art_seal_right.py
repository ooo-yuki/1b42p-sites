"""Круг красоты 1: тюленька вид строго сверху, глаза вправо. 16x16 RGBA."""
from PIL import Image

OUT = "tulenko.bratuxa.zomb.top/img/top_seal_right.png"

PAL = {
    "O": (34, 38, 45, 255),     # тёмная обводка
    "L": (217, 223, 230, 255),  # серо-белое тело
    "W": (242, 245, 247, 255),  # светлая спина
    "M": (167, 177, 187, 255),  # тень тон 1
    "D": (124, 133, 143, 255),  # тень тон 2
    "F": (154, 165, 176, 255),  # ласты
    "S": (73, 82, 92, 255),     # чистые пятна
    "E": (255, 255, 255, 255),  # белок глаза
    "B": (16, 18, 22, 255),     # зрачок у правого края = взгляд вправо
    "N": (34, 38, 45, 255),     # нос на кончике морды
    "H": (255, 255, 255, 255),  # блик на макушке
}

ART = [
    "................",  # 0
    "................",  # 1
    "....OO..........",  # 2  ласт верхний
    "...OFFFO........",  # 3
    "....OOFLLLLOO...",  # 4  основание ласта + верх тела
    "...OLLHWWLLMMLO.",  # 5  блик
    "..TOLLWSLLEBSMLO",  # 6  верхний глаз EB (зрачок справа)
    "..TTOLLSWSLLMMN.",  # 7  морда, нос справа
    "..TTOLLMSWLLMMN.",  # 8
    "..TOLLWSLLEBSDDO",  # 9  нижний глаз EB
    "...OLLWWWSLDDLO.",  # 10 тень two-tone снизу
    "....OOLLLLDDOO..",  # 11
    "...OFFFO........",  # 12 ласт нижний
    "....OO..........",  # 13
    "................",  # 14
    "................",  # 15
]

assert len(ART) == 16 and all(len(r) == 16 for r in ART)

img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
px = img.load()
for y, row in enumerate(ART):
    for x, ch in enumerate(row):
        if ch == ".":
            continue
        px[x, y] = PAL["M"] if ch == "T" else PAL[ch]

img.save(OUT)
print("saved", OUT)
