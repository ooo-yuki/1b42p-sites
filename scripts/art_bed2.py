#!/usr/bin/env python3
"""Круг красоты 2: top_bed — койка строго сверху, плоские прямоугольники.

16x16 RGBA, без света/градиентов (наказ судьи, вид прототипа).
Слои сверху вниз: тёмная обводка -> деревянная рама -> полосатый
матрас-ткань -> светлая подушка вверху -> рыжее одеяло внизу,
складки — плоские тёмные полосы, не тень.
Повтор: python3 scripts/art_bed2.py (из корня /root/sites)
"""
from PIL import Image, ImageDraw

W, H = 16, 16
O = (58, 62, 72, 255)      # обводка как у соседей
WOOD = (139, 94, 52, 255)  # рама деревом
POST = (90, 58, 30, 255)   # угловые стойки темнее
M1 = (205, 205, 215, 255)  # матрас светлая полоса
M2 = (168, 173, 190, 255)  # матрас тёмная полоса
PIL = (240, 238, 230, 255) # подушка светлая
SEAM = (200, 196, 184, 255)# шов подушки
GIN = (210, 110, 40, 255)  # одеяло рыжее
FOLD = (170, 82, 28, 255)  # складки одеяла — плоские полосы
EDGE = (150, 70, 25, 255)  # подгиб одеяла снизу

OUT = "tulenko.bratuxa.zomb.top/img/top_bed.png"

img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
d = ImageDraw.Draw(img)

# обводка — весь кадр
d.rectangle([0, 0, 15, 15], fill=O)
# рама деревом
d.rectangle([1, 1, 14, 14], fill=WOOD)
# угловые стойки
for x0, y0 in ((1, 1), (13, 1), (1, 13), (13, 13)):
    d.rectangle([x0, y0, x0 + 1, y0 + 1], fill=POST)
# матрас тканью в вертикальную полоску
for x in range(3, 13):
    d.rectangle([x, 2, x, 12], fill=M1 if x % 2 == 0 else M2)
# подушка светлая вверху + шов по центру
d.rectangle([4, 2, 11, 4], fill=PIL)
d.rectangle([4, 3, 11, 3], fill=SEAM)
# одеяло рыжее внизу + плоские складки + подгиб
d.rectangle([3, 8, 12, 12], fill=GIN)
for fx in (5, 9):
    d.rectangle([fx, 8, fx, 12], fill=FOLD)
d.rectangle([3, 12, 12, 12], fill=EDGE)

img.save(OUT)
print("saved", OUT, img.size)
