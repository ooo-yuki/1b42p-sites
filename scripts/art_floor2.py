#!/usr/bin/env python3
"""Круг красоты 2: top_floor — пол с фактурой, вид строго сверху.

16x16 RGBA. Было: ровная заливка cdcdd6 + рамка a0a0ac.
Стало: 4 плиты 8x8 со швами темнее, лёгкое зерно пятнами,
два-три тона серого, края клетки чуть темнее (сетка читается).
Без света: плоские прямоугольники, вид прототипа.
Углы прозрачные — как было.
Повтор: python3 scripts/art_floor2.py
"""
from PIL import Image

W, H = 16, 16
BASE_A = (205, 205, 214, 255)   # плита светлая (как было)
BASE_B = (191, 192, 201, 255)   # плита темнее — 2-й тон
SEAM = (142, 143, 152, 255)     # швы между плитами + край клетки

OUT = "tulenko.bratuxa.zomb.top/img/top_floor.png"

im = Image.new("RGBA", (W, H), (0, 0, 0, 0))
px = im.load()

# плиты 8x8: верх-лево и низ-право светлее, остальные темнее (шахматка)
for y in range(H):
    for x in range(W):
        tl = (x < 8 and y < 8) or (x >= 8 and y >= 8)
        px[x, y] = BASE_A if tl else BASE_B

# швы: средняя вертикаль и горизонталь
for i in range(16):
    px[7, i] = SEAM
    px[i, 7] = SEAM

# зерно пятнами — перекрёстные тона плит, новых тонов не добавляет
for x, y in [(2, 2), (11, 2), (4, 5), (13, 4), (2, 10), (5, 12),
              (10, 10), (13, 13), (3, 13), (11, 5)]:
    px[x, y] = BASE_B if (x < 8 and y < 8) or (x >= 8 and y >= 8) else BASE_A
for x, y in [(5, 3), (13, 1), (1, 6), (9, 3), (4, 9),
              (12, 8), (6, 14), (10, 13)]:
    px[x, y] = BASE_A if (x < 8 and y < 8) or (x >= 8 and y >= 8) else BASE_B

# край клетки тем же тёмным — сетка читается
for i in range(16):
    px[i, 0] = SEAM
    px[i, 15] = SEAM
    px[0, i] = SEAM
    px[15, i] = SEAM

# углы прозрачные — как было
for x, y in [(0, 0), (15, 0), (0, 15), (15, 15)]:
    px[x, y] = (0, 0, 0, 0)

im.save(OUT)
print("wrote", OUT)
